"""What the dashboard needs of each listing, and nothing else.

``listings.json`` is the search's source of truth and carries everything an agent or a script might want:
received claims, evidence notes, internal bookkeeping. The dashboard downloads and parses the whole file on first
load, so ``build`` writes a slimmed copy of it into ``dashboard/data/``: each listing keeps only the top-level
fields in :data:`DASHBOARD_FIELDS`, minus a few nested details no screen shows (:func:`slim_listing`).

The list is an allowlist. A field the dashboard starts to read must be added here, or a built dashboard will not
have it; ``tests/test_slim.py`` fails when a field that the example search carries and the dashboard's scripts
mention is missing from the list, which catches the usual way of forgetting.
"""
from __future__ import annotations

from typing import Any, Iterable

#: Top-level listing fields the dashboard (or the shortlist page it exports) reads. Grouped as docs/guides/data-model.md is.
DASHBOARD_FIELDS: frozenset[str] = frozenset({
    # identity and place
    "id", "building", "unit", "address", "neighborhood", "lat", "lon", "bbl", "bin",
    # the unit
    "beds", "baths", "sqft", "size", "floor", "floor_inferred", "exposure", "exposure_source", "layout", "available",
    "listed", "first_seen", "last_seen", "checked", "status", "stage", "tags", "dossier", "waived_must_have",
    # money
    "price", "price_history", "amenities", "features",
    # evidence the drawer and the research view show
    "reviews", "notes", "links", "sources", "video", "building_facts", "records", "site", "photo_review",
    # photos and plans
    "photos", "photos_local", "photos_meta", "photo_flags", "building_photos", "floorplan_images",
    # generated by the CLI
    "score", "commute",
})

#: Nested details that no screen reads: (path of keys; "*" matches any key, a list is walked) -> dropped key.
_NESTED_DROPS: tuple[tuple[tuple[str, ...], str], ...] = (
    (("commute", "*", "modes", "*"), "legs_arrive_by"),   # the arrival time the legs were planned for; the drawer shows the legs
)


def _drop(obj: Any, path: tuple[str, ...], key: str) -> Any:
    """A copy of ``obj`` with ``key`` removed wherever ``path`` leads; shares everything it does not change."""
    if isinstance(obj, list):
        return [_drop(v, path, key) for v in obj]
    if not isinstance(obj, dict):
        return obj
    if not path:
        return {k: v for k, v in obj.items() if k != key}
    head, rest = path[0], path[1:]
    return {k: (_drop(v, rest, key) if head == "*" or k == head else v) for k, v in obj.items()}


def slim_listing(listing: dict, fields: Iterable[str] = DASHBOARD_FIELDS) -> dict:
    """One listing reduced to what the dashboard reads. The input is left alone."""
    keep = frozenset(fields)
    out = {k: v for k, v in listing.items() if k in keep}
    for path, key in _NESTED_DROPS:
        if path[0] in out:
            out[path[0]] = _drop(out[path[0]], path[1:], key)
    return out


def slim_listings(listings: Iterable[dict]) -> list[dict]:
    return [slim_listing(L) for L in listings]
